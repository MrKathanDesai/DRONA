#!/usr/bin/env python3
"""Proposal comparison: CNN vs CNN+GRU vs lightweight transformer, from scratch.

    python scripts/make_features.py     # once
    python scripts/train_deep.py        # ~1-2 h on an M-series Mac
    python scripts/train_deep.py --arch cnn --epochs 5    # quick look

Same cached log-mel features, tiers and 1%-FPR operating point as the
baseline and the frozen pretrained encoder, so all rows compare. Results are
saved after every (model, tier), and a re-run skips what is already done
(delete reports/deep_audio.json to start over). Writes
reports/deep_audio.{json,md}.

Tier 2 uses `protocol.tier2(holdout=0.2)`: one fit, threshold from 20% of the
training recordings held out, instead of 5 grouped folds (5x the training
time). Nothing was tuned on any test split: one recipe, fixed epochs.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from dronedet.eval import protocol as P
from dronedet.models import deep as D
from dronedet.paths import DATA_DIR

FEATS = DATA_DIR / "features"
REPORTS = ROOT / "reports"
OUT = REPORTS / "deep_audio.json"
TARGET_FPR = 0.01
TIERS = ("tier1", "tier2", "tier3", "tier4")


def drone_vs_helicopter(df, tier, scores) -> float:
    t = df[df[tier] == "test"].assign(s=scores)
    t = t[t.category.isin(["drone", "helicopter"])]
    return float(roc_auc_score(t.y, t.s)) if t.y.nunique() == 2 else float("nan")


def run_tier(tier, X, df, make):
    if tier == "tier1":
        res, _ = P.tier1(X, df, make, TARGET_FPR)
        return res
    if tier == "tier2":
        return P.tier2(X, df, make, TARGET_FPR, holdout=0.2)
    col = f"split_{tier}"
    if tier == "tier3":
        res, fa, model, _ = P._train_val_test(X, df, col, make, TARGET_FPR)
    else:
        res, fa, model, _ = P.tier4(X, df, make, TARGET_FPR)
    te = (df[col] == "test").values
    res["drone_vs_helicopter_auc"] = drone_vs_helicopter(
        df, col, model.predict_proba(X[te])[:, 1])
    res["false_alarms_by_category"] = fa.reset_index().to_dict("records")
    res["train_loss"] = model.history_
    return res


def fmt(r):
    lo, hi = r["pr_auc_ci95"]
    return (f"| {r['pr_auc']:.3f} [{lo:.3f}, {hi:.3f}] | {r['roc_auc']:.3f} "
            f"| {r['recall']:.3f} | {r['fpr']:.4f} ({r['false_alarms']}/{r['negatives']}) "
            f"| {r['accuracy']:.3f} | {r['f1']:.3f} |")


def write_md(report):
    rows = []
    for tier in TIERS:
        for arch, r in report["models"].items():
            if tier in r:
                rows.append(f"| {arch} | {tier.replace('tier', 'tier ')} " + fmt(r[tier]))
    heli = [f"| {a} | " + " | ".join(
        f"{r[t]['drone_vs_helicopter_auc']:.3f}" if t in r else "n/a"
        for t in ("tier3", "tier4")) + " |" for a, r in report["models"].items()]
    md = [
        "# Audio models trained from scratch: CNN vs CNN+GRU vs transformer", "",
        "The proposal's audio comparison. All three see the same cached 1 s "
        "log-mel (128 x 63), with the clip's mean level removed, per-band "
        "standardisation from train, SpecAugment, AdamW with a one-cycle "
        f"schedule and {report['epochs']} fixed epochs. Threshold at "
        f"{TARGET_FPR:.0%} FPR on validation negatives, unchanged on test. "
        "Generated by `scripts/train_deep.py`.", "",
        "| model | parameters |", "|---|---|",
        *[f"| {a} | {D.n_params(a):,} |" for a in report["models"]], "",
        "- tier 1: held-out recordings, same indoor corpus",
        "- tier 2: train Bebop, test Mambo; threshold from 20% of training "
        "recordings held out (one fit, not 5 folds)",
        "- tier 3: train indoor, test outdoor Svanström",
        "- tier 4: tier 3 plus ITU ARIS outdoor drones in training, source-balanced", "",
        "Accuracy and F1 depend on the test set's drone share (12-33% here, "
        "far above real life), so read PR-AUC and recall at the fixed false-alarm "
        "rate first.", "",
        "| model | tier | PR-AUC [95% CI] | ROC-AUC | recall @ val-1%-FPR "
        "| test FPR (false alarms) | accuracy | F1 |",
        "|---|---|---|---|---|---|---|---|", *rows, "",
        "## Drone vs helicopter ROC-AUC (outdoor test)", "",
        "| model | tier 3 | tier 4 |", "|---|---|---|", *heli, "",
    ]
    (REPORTS / "deep_audio.md").write_text("\n".join(md))
    return md


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--arch", nargs="*", default=list(D.ARCHS))
    ap.add_argument("--tiers", nargs="*", default=list(TIERS))
    ap.add_argument("--epochs", type=int, default=20)
    args = ap.parse_args()

    X = np.load(FEATS / "X.npy")
    df = P.with_category(pd.read_parquet(FEATS / "index.parquet"))
    report = json.loads(OUT.read_text()) if OUT.exists() else {}
    if report.get("epochs") not in (None, args.epochs):
        print(f"  {OUT.name} was made with {report['epochs']} epochs; delete it to change")
        return 1
    report.update(target_fpr=TARGET_FPR, epochs=args.epochs)
    report.setdefault("models", {})
    REPORTS.mkdir(exist_ok=True)

    for arch in args.arch:
        def make(arch=arch):
            return D.DeepClassifier(arch, epochs=args.epochs)
        done = report["models"].setdefault(arch, {})
        for tier in args.tiers:
            if tier in done:
                continue
            t0 = time.time()
            print(f"  {arch}: {tier} ...", flush=True)
            done[tier] = run_tier(tier, X, df, make)
            done[tier]["seconds"] = round(time.time() - t0, 1)
            r = done[tier]
            print(f"    PR-AUC {r['pr_auc']:.3f}  recall {r['recall']:.3f}  "
                  f"FPR {r['fpr']:.4f}  ({r['seconds']:.0f} s)", flush=True)
            OUT.write_text(json.dumps(report, indent=2))
    print("\n".join(write_md(report)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
