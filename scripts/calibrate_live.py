#!/usr/bin/env python3
"""Calibrate the live page's alarm rule on validation recordings.

    python scripts/calibrate_live.py

The live page (console/) raises "drone" after k drone windows in a row. The
window threshold is already fixed by the detector (1% false alarms per window
on validation negatives); this chooses k, at the recording level, where it
matters to an operator: does a drone recording raise an alarm, and does a
background recording raise a false one?

Rule, fixed before any result was seen: among k = 1..4, take the k with the
fewest false-alarm recordings while still catching at least 90% of the drone
recordings that the most sensitive k catches. Chosen on tier-4 validation
recordings only; the outdoor Svanström test recordings are reported after.

Writes console/calibration.json (read by the live page) and
reports/live_calibration.md.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT))

import joblib
import numpy as np
import pandas as pd

from console.server import Session
from dronedet.paths import DATA_DIR

KS = (1, 2, 3, 4)
HOLD = 3
KEEP = 0.90


def recordings(df: pd.DataFrame, states: np.ndarray):
    """(label, states in time order) per recording."""
    d = df.assign(state=states)
    for _, g in d.groupby("group_id"):
        g = g.sort_values(["path", "start_s"], na_position="first")
        yield int(g.y.iloc[0]), list(g.state)


def score(recs, k: int) -> dict:
    hit = {0: [], 1: []}
    for y, states in recs:
        s = Session(confirm=k, hold=HOLD)
        hit[y].append(any(s.step(x) == "drone" for x in states))
    return {"drone_recordings_alarmed": float(np.mean(hit[1])),
            "background_recordings_alarmed": float(np.mean(hit[0])),
            "drone_recordings": len(hit[1]), "background_recordings": len(hit[0])}


def main() -> int:
    F = np.load(DATA_DIR / "embeddings" / "E.npy")
    df = pd.read_parquet(DATA_DIR / "embeddings" / "index.parquet")
    df["y"] = (df.label == "drone").astype(int)
    det = joblib.load(DATA_DIR / "models" / "detector.joblib")
    states = np.asarray(det.assess(F)["state"])

    out = {}
    for name, mask in (("validation", df.split_tier4 == "val"),
                       ("test (outdoor Svanström)", df.split_tier4 == "test")):
        recs = list(recordings(df[mask], states[mask.values]))
        out[name] = {k: score(recs, k) for k in KS}

    val = out["validation"]
    best = max(v["drone_recordings_alarmed"] for v in val.values())
    ok = [k for k in KS if val[k]["drone_recordings_alarmed"] >= KEEP * best]
    k = min(ok, key=lambda k: (val[k]["background_recordings_alarmed"], k))

    (ROOT / "console" / "calibration.json").write_text(
        json.dumps({"confirm": k, "hold": HOLD, "source": "scripts/calibrate_live.py"}, indent=2) + "\n")
    rep = {"hold": HOLD, "keep": KEEP, "chosen_confirm": k, "results": out}
    (ROOT / "reports" / "live_calibration.json").write_text(json.dumps(rep, indent=2))

    md = ["# Live alarm rule: calibration", "",
          f"The live page calls \"drone\" after *k* drone windows in a row and holds the call for "
          f"{HOLD} windows. *k* is chosen on tier-4 validation recordings: the fewest false-alarm "
          f"recordings while catching at least {KEEP:.0%} of the drone recordings the most "
          f"sensitive *k* catches. **Chosen: k = {k}.** Generated by `scripts/calibrate_live.py`.", ""]
    for name, res in out.items():
        n = next(iter(res.values()))
        md += [f"## {name} ({n['drone_recordings']} drone, {n['background_recordings']} background recordings)", "",
               "| k | drone recordings alarmed | background recordings alarmed |", "|---|---|---|"]
        md += [f"| {kk}{' (chosen)' if kk == k else ''} | {v['drone_recordings_alarmed']:.2f} | "
               f"{v['background_recordings_alarmed']:.3f} |" for kk, v in res.items()]
        md.append("")
    md.append("Validation recordings are indoor DroneAudioDataset and ITU ARIS; the test set is "
              "outdoor, where window-level recall is known to be weak (`outdoor_audio.md`).")
    (ROOT / "reports" / "live_calibration.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
